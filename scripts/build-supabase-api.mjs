import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const generatedDirectory = join(
  projectRoot,
  "supabase/functions/payroll-api/generated",
);

function replaceRequired(source, search, replacement, description) {
  if (!source.includes(search)) {
    throw new Error(
      `The existing payroll implementation changed: could not adapt ${description}.`,
    );
  }
  return source.replaceAll(search, replacement);
}

await mkdir(generatedDirectory, { recursive: true });

let schema = await readFile(join(projectRoot, "db/schema.ts"), "utf8");
schema = replaceRequired(
  schema,
  'import {\n  index,\n  integer,\n  real,\n  sqliteTable,\n  text,\n  uniqueIndex,\n} from "drizzle-orm/sqlite-core";',
  'import { doublePrecision, index, integer, pgTable, text, uniqueIndex } from "drizzle-orm/pg-core";',
  "the SQLite schema imports for PostgreSQL",
);
schema = replaceRequired(schema, "sqliteTable(", "pgTable(", "PostgreSQL tables");
schema = replaceRequired(schema, "real(", "doublePrecision(", "salary number columns");
schema = replaceRequired(
  schema,
  'integer("id").primaryKey({ autoIncrement: true })',
  'integer("id").generatedByDefaultAsIdentity().primaryKey()',
  "PostgreSQL identity columns",
);

let route = await readFile(
  join(projectRoot, "app/api/app-data/route.ts"),
  "utf8",
);
route = replaceRequired(
  route,
  'import { getAuthenticatedUser, type AuthenticatedUser } from "../../auth";',
  'import type { AuthenticatedUser } from "../supabase-runtime.ts";',
  "Supabase-authenticated identity",
);
route = replaceRequired(
  route,
  'import { getDb, getRawDb } from "../../../db";',
  'import { getDb, getRawDb } from "../supabase-runtime.ts";',
  "the Supabase database adapter",
);
route = replaceRequired(
  route,
  'from "../../../db/schema";',
  'from "./schema.ts";',
  "the PostgreSQL payroll schema",
);
route = replaceRequired(
  route,
  'from "../../../lib/payroll-calculations";',
  'from "./payroll-calculations.ts";',
  "the existing payroll calculations",
);
route = replaceRequired(
  route,
  'from "../../../lib/access-control";',
  'from "./access-control.ts";',
  "the existing role and permission checks",
);
route = replaceRequired(
  route,
  'from "../../../lib/payroll-operations";',
  'from "./payroll-operations.ts";',
  "the accommodation, date-period, and access-scope operations",
);
route = replaceRequired(
  route,
  "async function requireAppAccess(db: Db): Promise<AppAccess> {",
  "async function requireAppAccess(db: Db, identity: AuthenticatedUser | null): Promise<AppAccess> {",
  "per-request identity injection",
);
route = replaceRequired(
  route,
  "  const identity = await getAuthenticatedUser();\n",
  "",
  "the previous ChatGPT/Cloudflare authentication provider",
);
route = replaceRequired(
  route,
  "const access = await requireAppAccess(db);",
  "const access = await requireAppAccess(db, identity);",
  "authenticated API handlers",
);
route = replaceRequired(
  route,
  "export async function GET() {",
  "export async function GET(identity: AuthenticatedUser | null) {",
  "the authenticated GET handler",
);
route = replaceRequired(
  route,
  "export async function POST(request: Request) {",
  "export async function POST(request: Request, identity: AuthenticatedUser | null) {",
  "the authenticated POST handler",
);
route = replaceRequired(
  route,
  "await ensureDemoData();",
  "/* Supabase production databases intentionally start without demo payroll records. */",
  "production-safe removal of automatic demonstration records",
);
route = route.replace(
  "/UNIQUE constraint failed: vendors\\.code/i",
  "/UNIQUE constraint failed: vendors\\.code|vendors_code_(?:unique|key)/i",
);
route = route.replace(
  "/UNIQUE constraint failed: shift_definitions\\.vendor_id, shift_definitions\\.name/i",
  "/UNIQUE constraint failed: shift_definitions\\.vendor_id, shift_definitions\\.name|shift_client_name_unique/i",
);
route = route.replace(
  "/UNIQUE constraint failed: employees\\.employee_code/i",
  "/UNIQUE constraint failed: employees\\.employee_code|employees_employee_code_(?:unique|key)/i",
);

const banner =
  "// Generated by npm run prepare:supabase. Edit the original Joy payroll source instead.\n";

await Promise.all([
  writeFile(join(generatedDirectory, "schema.ts"), banner + schema),
  writeFile(join(generatedDirectory, "route.ts"), banner + route),
  readFile(join(projectRoot, "lib/access-control.ts"), "utf8").then((source) =>
    writeFile(join(generatedDirectory, "access-control.ts"), banner + source),
  ),
  readFile(join(projectRoot, "lib/payroll-calculations.ts"), "utf8").then(
    (source) =>
      writeFile(join(generatedDirectory, "payroll-calculations.ts"), banner + source),
  ),
  readFile(join(projectRoot, "lib/payroll-operations.ts"), "utf8").then(
    (source) =>
      writeFile(join(generatedDirectory, "payroll-operations.ts"), banner + source),
  ),
]);

console.log(
  "Prepared the complete Joy payroll API, PostgreSQL schema, calculations, and role checks for Supabase.",
);
